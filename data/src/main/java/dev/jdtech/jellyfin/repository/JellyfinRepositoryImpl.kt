    override suspend fun getAudioOnlyStream(
        itemId: UUID,
        mediaSourceId: String,
        bitrate: Int,
    ): FindroidTranscodeStream? =
        withContext(Dispatchers.IO) {
            val accessToken = jellyfinApi.api.accessToken ?: return@withContext null
            // The server's audio playlist works for videos too: it leaves the picture out
            val url =
                jellyfinApi.api.createUrl(
                    "/Audio/{itemId}/main.m3u8",
                    pathParameters = mapOf("itemId" to itemId),
                    queryParameters =
                        mapOf(
                            "mediaSourceId" to mediaSourceId,
                            "audioCodec" to "aac",
                            "audioBitRate" to bitrate,
                            "maxAudioChannels" to 2,
                            "segmentContainer" to "ts",
                            "playSessionId" to UUID.randomUUID().toString().replace("-", ""),
                            "deviceId" to jellyfinApi.api.deviceInfo.id,
                            "ApiKey" to accessToken,
                        ),
                )
            FindroidTranscodeStream(url = url, subtitles = emptyList())
        }

    override suspend fun getShowServerSize(seriesId: UUID): FindroidServerSize? =
        withContext(Dispatchers.IO) {
            try {
                val episodes =
                    jellyfinApi.showApi
                        .getEpisodes(
                            seriesId,
                            jellyfinApi.userId!!,
                            fields = listOf(ItemFields.MEDIA_SOURCES),
                            isMissing = false,
                            enableImages = false,
                            enableUserData = false,
                        )
                        .content
                        .items
                // Every version of every episode, as that is what is stored on the server
                val sources = episodes.flatMap { episode -> episode.mediaSources.orEmpty() }
                val bytes = sources.distinctBy { it.id }.sumOf { it.size ?: 0L }
                FindroidServerSize(episodeCount = episodes.size, bytes = bytes)
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Timber.e(e)
                null
            }
        }

    override suspend fun getTranscodeStream(
        itemId: UUID,
        mediaSourceId: String,
        maxWidth: Int,
        maxHeight: Int,
        maxBitrate: Int,
    ): FindroidTranscodeStream? =
        withContext(Dispatchers.IO) {
            val sizeConditions =
                listOf(
                    ProfileCondition(
                        condition = ProfileConditionType.LESS_THAN_EQUAL,
                        property = ProfileConditionValue.WIDTH,
                        value = maxWidth.toString(),
                        isRequired = false,
                    ),
                    ProfileCondition(
                        condition = ProfileConditionType.LESS_THAN_EQUAL,
                        property = ProfileConditionValue.HEIGHT,
                        value = maxHeight.toString(),
                        isRequired = false,
                    ),
                )
            val response =
                jellyfinApi.mediaInfoApi
                    .getPostedPlaybackInfo(
                        itemId,
                        PlaybackInfoDto(
                            userId = jellyfinApi.userId!!,
                            mediaSourceId = mediaSourceId,
                            maxStreamingBitrate = maxBitrate,
                            enableDirectPlay = false,
                            enableDirectStream = false,
                            enableTranscoding = true,
                            allowVideoStreamCopy = false,
                            allowAudioStreamCopy = true,
                            autoOpenLiveStream = true,
                            deviceProfile =
                                DeviceProfile(
                                    name = "Findroid transcode",
                                    maxStreamingBitrate = maxBitrate,
                                    maxStaticBitrate = maxBitrate,
                                    directPlayProfiles = emptyList(),
                                    transcodingProfiles =
                                        listOf(
                                            TranscodingProfile(
                                                container = "ts",
                                                type = DlnaProfileType.VIDEO,
                                                videoCodec = "h264",
                                                audioCodec = "aac",
                                                protocol = MediaStreamProtocol.HLS,
                                                context = EncodingContext.STREAMING,
                                                maxAudioChannels = "2",
                                                minSegments = 1,
                                                breakOnNonKeyFrames = true,
                                                conditions = emptyList(),
                                            )
                                        ),
                                    containerProfiles = emptyList(),
                                    codecProfiles =
                                        listOf(
                                            CodecProfile(
                                                type = CodecType.VIDEO,
                                                codec = "h264",
                                                conditions = sizeConditions,
                                                applyConditions = emptyList(),
                                            )
                                        ),
                                    subtitleProfiles =
                                        listOf("srt", "subrip", "ass", "ssa", "vtt", "webvtt").map {
                                            SubtitleProfile(it, SubtitleDeliveryMethod.EXTERNAL)
                                        },
                                ),
                        ),
                    )
                    .content
            val source =
                response.mediaSources.firstOrNull { it.id == mediaSourceId }
                    ?: response.mediaSources.firstOrNull()
                    ?: return@withContext null
            val transcodingUrl = source.transcodingUrl
            if (transcodingUrl.isNullOrBlank()) {
                Timber.w("Server returned no transcoding url (error: ${response.errorCode})")
                return@withContext null
            }
            val subtitles =
                source.mediaStreams
                    .orEmpty()
                    .filter {
                        it.type == MediaStreamType.SUBTITLE &&
                            it.deliveryMethod == SubtitleDeliveryMethod.EXTERNAL &&
                            !it.deliveryUrl.isNullOrBlank()
                    }
                    .map { it.toFindroidMediaStream(this@JellyfinRepositoryImpl) }
            FindroidTranscodeStream(
                url = limitSize(getBaseUrl() + transcodingUrl, maxWidth, maxHeight),
                subtitles = subtitles,
            )
        }

    /**
     * Makes sure the stream address asks for at most the given size, whatever the server derived
     * from the device profile.
     */
    private fun limitSize(url: String, maxWidth: Int, maxHeight: Int): String {
        val uri = Uri.parse(url)
        val builder = uri.buildUpon().clearQuery()
        for (name in uri.queryParameterNames) {
            if (name.equals("MaxWidth", ignoreCase = true)) continue
            if (name.equals("MaxHeight", ignoreCase = true)) continue
            for (value in uri.getQueryParameters(name)) {
                builder.appendQueryParameter(name, value)
            }
        }
        builder.appendQueryParameter("MaxWidth", maxWidth.toString())
        builder.appendQueryParameter("MaxHeight", maxHeight.toString())
        return builder.build().toString()
    }

    override suspend fun getSegments(itemId: UUID): List<FindroidSegment> =
        withContext(Dispatchers.IO) {
            val databaseSegments = database.getSegments(itemId).map { it.toFindroidSegment() }

            if (databaseSegments.isNotEmpty()) {
                return@withContext databaseSegments
            }

            try {
                val apiSegments =
                    jellyfinApi.mediaSegmentApi.getItemSegments(itemId).content.items.map {
                        it.toFindroidSegment()
                    }

                return@withContext apiSegments
            } catch (e: Exception) {
                Timber.e(e)
                return@withContext emptyList()
            }
        }

    override suspend fun getTrickplayData(itemId: UUID, width: Int, index: Int): ByteArray? =
        withContext(Dispatchers.IO) {
            try {
                try {
                    val sources = File(context.filesDir, "trickplay/$itemId").listFiles()
                    if (sources != null) {
                        return@withContext File(sources.first(), index.toString()).readBytes()
                    }
                } catch (_: Exception) {}

                return@withContext jellyfinApi.trickPlayApi
                    .getTrickplayTileImage(itemId, width, index)
                    .content
            } catch (_: Exception) {
                return@withContext null
            }
        }

