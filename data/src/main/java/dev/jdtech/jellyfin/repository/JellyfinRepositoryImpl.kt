            database.setFavorite(jellyfinApi.userId!!, itemId, false)
            try {
                jellyfinApi.userDataApi.unmarkFavoriteItem(itemId)
            } catch (_: Exception) {
                database.setUserDataToBeSynced(jellyfinApi.userId!!, itemId, true)
            }
        }
    }

    override suspend fun markAsPlayed(itemId: UUID) {
        withContext(Dispatchers.IO) {
            database.setPlayed(jellyfinApi.userId!!, itemId, true)
            try {
                jellyfinApi.userDataApi.markPlayedItem(itemId)
            } catch (_: Exception) {
                database.setUserDataToBeSynced(jellyfinApi.userId!!, itemId, true)
            }
        }
    }

    override suspend fun markAsUnplayed(itemId: UUID) {
        withContext(Dispatchers.IO) {
            database.setPlayed(jellyfinApi.userId!!, itemId, false)
            try {
                jellyfinApi.userDataApi.markUnplayedItem(itemId)
            } catch (_: Exception) {
                database.setUserDataToBeSynced(jellyfinApi.userId!!, itemId, true)
            }
        }
    }

    override fun getBaseUrl() = jellyfinApi.api.baseUrl.orEmpty()

    override suspend fun updateDeviceName(name: String) {
        withContext(Dispatchers.IO) {
            jellyfinApi.jellyfin.deviceInfo?.id?.let { id ->
                jellyfinApi.deviceApi.updateDeviceOptions(
                    id,
                    DeviceOptionsDto(0, customName = name),
                )
            }
        }
    }

    override suspend fun getUserConfiguration(): UserConfiguration =
        withContext(Dispatchers.IO) { jellyfinApi.userApi.getCurrentUser().content.configuration!! }

    override suspend fun getDownloads(): List<FindroidItem> =
        withContext(Dispatchers.IO) {
            val items = mutableListOf<FindroidItem>()
            items.addAll(
                database
                    .getMoviesByServerId(appPreferences.getValue(appPreferences.currentServer)!!)
                    .map { it.toFindroidMovie(database, jellyfinApi.userId!!) }
            )
            items.addAll(
                database
                    .getShowsByServerId(appPreferences.getValue(appPreferences.currentServer)!!)
                    .map { it.toFindroidShow(database, jellyfinApi.userId!!) }
            )
            items
        }

    override suspend fun getDownloadedEpisodes(): List<FindroidEpisode> =
        withContext(Dispatchers.IO) {
            database
                .getEpisodesByServerId(appPreferences.getValue(appPreferences.currentServer)!!)
                .map { it.toFindroidEpisode(database, jellyfinApi.userId!!) }
        }

    override suspend fun getPlaylists(): List<FindroidPlaylist> =
        withContext(Dispatchers.IO) {
            jellyfinApi.libraryApi
                .getItems(
                    jellyfinApi.userId!!,
                    includeItemTypes = listOf(BaseItemKind.PLAYLIST),
                    recursive = true,
                    sortBy = listOf(ItemSortBy.fromName(SortBy.NAME.sortString)),
                )
                .content
                .items
                // Findroid only plays video, so music playlists are left out
                .filter { it.mediaType != MediaType.AUDIO }
                .map { it.toFindroidPlaylist(this@JellyfinRepositoryImpl) }
        }

    override suspend fun getPlaylistItems(playlistId: UUID): List<FindroidItem> =
        withContext(Dispatchers.IO) {
            jellyfinApi.playlistApi
                .getPlaylistItems(
                    playlistId = playlistId,
                    userId = jellyfinApi.userId!!,
                    fields = listOf(ItemFields.CHAPTERS, ItemFields.TRICKPLAY),
                )
                .content
                .items
                .mapNotNull { item ->
                    when (item.type) {
                        BaseItemKind.MOVIE,
                        BaseItemKind.EPISODE ->
                            item.toFindroidItem(this@JellyfinRepositoryImpl, database)
                        else -> null
                    }
                }
        }

    override fun getUserId(): UUID {
        return jellyfinApi.userId!!
    }
